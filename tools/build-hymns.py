"""Build js/hymns.js from data/*.json.
Sources:
  data/lsb-titles.json  LSB pew-edition titles (singpraises.net LSB collection)
  data/lsb-index.json   LCMS Lutheran Hymn Index: alternate titles + Scripture
  data/hotd.json        LCMS 'LSB Hymn of the Day' list
  data/tfbf.json        This Far By Faith (1999): titles, first lines, tunes, topics (hymnary.org)
"""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda f: json.load(open(os.path.join(root, 'data', f)))
titles, idx, hd = J('lsb-titles.json'), J('lsb-index.json'), J('hotd.json')
tf = J('tfbf.json') if os.path.exists(os.path.join(root, 'data', 'tfbf.json')) else {'hymns': {}, 'topics': {}}

# LSB contents (CPH, LSB Devotional Edition table of contents)
SECTIONS = [
 ('The Church Year', [('Advent',331,357),('Christmas',358,393),('Epiphany',394,412),('Transfiguration',413,417),('Lent',418,440),
   ('Holy Week',441,456),('Easter',457,490),('Ascension',491,495),('Pentecost',496,503),('Holy Trinity',504,507),('End Times',508,516),
   ('Feasts and Festivals',517,522)]),
 ('Person and Work of Christ', [('Redeemer',523,554),('Justification',555,576)]),
 ('The Christian Church', [('The Word of God',577,589),('Holy Baptism',590,593),('Baptismal Life',594,605),('Confession and Absolution',606,616),
   ("The Lord's Supper",617,643),('The Church',644,654),('The Church Militant',655,669),('The Church Triumphant',670,680),('Ordination, Installation',681,682)]),
 ('The Christian Life', [('Sanctification',683,707),('Trust',708,740),('Hope and Comfort',741,765),('Prayer',766,780),('Stewardship',781,789),
   ('Praise and Adoration',790,822),('Mission and Witness',823,840),('Society',841,852),('Vocation',853,857),('Marriage',858,860),('Christian Home and Education',861,867)]),
 ('Times and Seasons', [('Morning',868,876),('Evening',877,891),('Harvest and Thanksgiving',892,895),('New Year',896,900)]),
 ('The Service', [('Beginning of Service',901,916),('Close of Service',917,924),('Biblical Canticles',925,941),('Liturgical Music',942,963),('Nation and National Songs',964,966)]),
]
# This Far By Faith topics (hymnary.org) → the same section names where they match
TF_MAP = {'Advent':'Advent','Christmas':'Christmas','Epiphany':'Epiphany','Lent':'Lent','Holy Week, The Three Days':'Holy Week','Good Friday':'Holy Week',
 'Maundy Thursday':'Holy Week','Easter':'Easter','Ascension':'Ascension','Pentecost':'Pentecost','Holy Trinity':'Holy Trinity','Last Times':'End Times',
 'Christ the King/Reign of Christ':'End Times','All Saints Day':'Feasts and Festivals','Lesser Festivals':'Feasts and Festivals','Mary, Mother of Our Lord':'Feasts and Festivals',
 'Holy innocents':'Feasts and Festivals','Name of Jesus':'Feasts and Festivals','Holy Baptism':'Holy Baptism','Affirmation of Baptism':'Baptismal Life',
 'Holy Communion':"The Lord's Supper",'Healing, Forgiveness':'Confession and Absolution','Prayer':'Prayer','Praise, Thanksgiving':'Praise and Adoration',
 'Justice, Society':'Society','Marriage':'Marriage','Morning, Evening':'Morning','Hope, Comfort':'Hope and Comfort','Burial':'Hope and Comfort',
 'Heaven, Eternal Life':'The Church Triumphant','Invitation to Discipleship':'Mission and Witness','Gathering':'Beginning of Service','Offertory':'Stewardship'}
tf_sec = {}
for topic, nums in tf.get('topics', {}).items():
    for n in nums:
        tf_sec.setdefault(n, [])
        s = TF_MAP.get(topic, topic)
        if s not in tf_sec[n]: tf_sec[n].append(s)
lsb = {n: [t, (idx.get(n, {}) or {}).get('s', ''), [a for a in (idx.get(n, {}) or {}).get('t', []) if a != t]] for n, t in titles.items()}
for n, v in idx.items():
    if n not in lsb: lsb[n] = [hd['preferred'].get(n) or v['t'][0], v.get('s', ''), v['t'][1:]]
tfbf = {n: [h.get('t') or h.get('f'), h.get('f', ''), h.get('tune', ''), tf_sec.get(n, [])] for n, h in tf.get('hymns', {}).items()}
D = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))
out = f"""/* Generated by tools/build-hymns.py — do not edit by hand.
 * LSB: number -> [title, Scripture, alternate titles]. Titles: LSB pew edition; Scripture/alternates: LCMS Lutheran Hymn Index.
 * LSB_SECTIONS: LSB table of contents (CPH).  TFBF: This Far By Faith (1999) number -> [title, first line, tune, sections].
 * HOTD: LCMS 'LSB Hymn of the Day' by day and series.
 */
(function (root) {{
  const LSB = {D(lsb)};
  const LSB_SECTIONS = {D(SECTIONS)};
  const TFBF = {D(tfbf)};
  const PREFERRED = {D(hd['preferred'])};
  const HOTD = {D(hd['hotd'])};
  function sectionOf(n) {{ n = +n; for (const [g, list] of LSB_SECTIONS) for (const [s, a, b] of list) if (n >= a && n <= b) return {{ group: g, section: s }}; return n >= 967 ? {{ group: 'Additional Hymns', section: 'Service Builder only' }} : null; }}
  const titleFor = (n, book = 'LSB') => book === 'TFBF' ? (TFBF[n] ? TFBF[n][0] : '') : (LSB[n] ? LSB[n][0] : PREFERRED[n] || '');
  const ambiguous = () => false;
  function hotd(key, series) {{ const e = HOTD[key]; if (!e) return []; return (e[series] || e.all || []).map((n) => ({{ n, title: titleFor(n) }})); }}
  // Every hymn in both books, for browsing and searching
  function all() {{
    const out = [];
    for (const [n, [t, s, alts]] of Object.entries(LSB)) {{ const sec = sectionOf(n); out.push({{ book: 'LSB', n: +n, id: 'LSB ' + n, title: t, scripture: s, alts, sections: sec ? [sec.section] : [], group: sec ? sec.group : '' }}); }}
    for (const [n, [t, f, tune, secs]] of Object.entries(TFBF)) out.push({{ book: 'TFBF', n: +n, id: 'TFBF ' + n, title: t, first: f, tune, scripture: '', alts: [], sections: secs, group: '' }});
    return out;
  }}
  root.HYMNS = {{ LSB, LSB_SECTIONS, TFBF, PREFERRED, HOTD, titleFor, hotd, ambiguous, sectionOf, all }};
}})(typeof window !== 'undefined' ? window : globalThis);
"""
open(os.path.join(root, 'js', 'hymns.js'), 'w').write(out)
print('LSB', len(lsb), 'TFBF', len(tfbf), 'bytes', len(out))
